int64_t entity_load(uint8_t* payload, int32_t length) {
    JSValue result = call_with_payload(hookEntityLoad, payload, length, "an entity script's load");
    int64_t packed = pack_result(result);
    JS_FreeValue(ctx, result);
    return packed;
}

