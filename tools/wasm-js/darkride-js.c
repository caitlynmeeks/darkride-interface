#define MAX_ENCODE_DEPTH 64
#define JS_STACK_SIZE (6 * 1024 * 1024)  /* under the 8 MB the module is linked with */

static JSRuntime* rt;
static JSContext* ctx;
static JSClassID hostObjectClassId;

/* the shim's functions the bridge calls: set once at start from what the shim returns */
static JSValue hookWrapObject = JS_UNDEFINED;       /* (handle, className) -> object */
static JSValue hookRegisterCallback = JS_UNDEFINED; /* (function) -> id */
static JSValue hookOnSignal = JS_UNDEFINED;         /* (connection, args) */
static JSValue hookOnCallback = JS_UNDEFINED;       /* (id, args) */
static JSValue hookStart = JS_UNDEFINED;            /* () */
static JSValue hookStop = JS_UNDEFINED;             /* () */
static JSValue hookEntityLoad = JS_UNDEFINED;       /* (payload) -> null or an error record */
static JSValue hookEntityUnload = JS_UNDEFINED;     /* (payload) */
static JSValue hookEntityHas = JS_UNDEFINED;        /* (payload) -> 0 or 1 */
static JSValue hookEntityCall = JS_UNDEFINED;       /* (payload) -> the method's result */
static JSValue hookAfterInterruption = JS_UNDEFINED; /* () -> the entity script that was running, state reset */

/* The entity script that was running when the host interrupted a call, until the host takes it (interrupted_entity). */
static char interruptedEntity[64];

/* --- logging and errors ---------------------------------------------------------------------------------------- */

static void log_text(int level, const char* text, size_t length) {
    dr_log(level, text, (int32_t)length);
}

static void log_string(int level, const char* text) {
    log_text(level, text, strlen(text));
}

/* The pending exception, logged as "<message>\n<stack>" at the error level, and cleared. An interruption (the host
   said to stop: QuickJS's only uncatchable error) is a debug line: the host reports why. */
static int interrupt_handler(JSRuntime* runtime, void* opaque);

/* After an interruption unwound a call: the shim says which entity script was running and resets what the
   unwinding skipped (no catch or finally runs for an uncatchable error). The host may still be saying "stop"
   (the limit is still passed), so the interrupt handler is off while the shim answers. */
static void after_interruption(void) {
    if (!ctx || !JS_IsFunction(ctx, hookAfterInterruption)) {
        return;
    }
    JS_SetInterruptHandler(rt, NULL, NULL);
    JSValue entity = JS_Call(ctx, hookAfterInterruption, JS_UNDEFINED, 0, NULL);
    JS_SetInterruptHandler(rt, interrupt_handler, NULL);
    if (JS_IsException(entity)) {
        JS_FreeValue(ctx, JS_GetException(ctx));
        return;
    }
    if (JS_IsString(entity) && interruptedEntity[0] == 0) {
        size_t length = 0;
        const char* text = JS_ToCStringLen(ctx, &length, entity);
        if (text && length > 0 && length < sizeof(interruptedEntity)) {
            memcpy(interruptedEntity, text, length);
            interruptedEntity[length] = 0;
        }
        if (text) JS_FreeCString(ctx, text);
    }
    JS_FreeValue(ctx, entity);
}

static void report_exception(const char* where) {
    JSValue exception = JS_GetException(ctx);
    if (JS_IsUncatchableError(exception)) {
        JS_FreeValue(ctx, exception);
        log_string(DR_LOG_DEBUG, "interrupted by the host");
        after_interruption();
        return;
    }
    const char* message = NULL;
    const char* stack = NULL;
    size_t messageLength = 0;
    size_t stackLength = 0;
    JSValue stackValue = JS_UNDEFINED;
    if (JS_IsError(exception)) {
        stackValue = JS_GetPropertyStr(ctx, exception, "stack");
    }
    message = JS_ToCStringLen(ctx, &messageLength, exception);
    if (!JS_IsUndefined(stackValue)) {
        stack = JS_ToCStringLen(ctx, &stackLength, stackValue);
    }
    size_t whereLength = where ? strlen(where) : 0;
    size_t total = whereLength + 2 + messageLength + 1 + stackLength + 1;
    char* text = (char*)malloc(total);
    if (text) {
        size_t n = 0;
        if (whereLength) {
            memcpy(text + n, where, whereLength);
            n += whereLength;
            text[n++] = ':';
            text[n++] = ' ';
        }
        if (message) {
            memcpy(text + n, message, messageLength);
            n += messageLength;
        }
        if (stack && stackLength) {
            text[n++] = '\n';
            memcpy(text + n, stack, stackLength);
            n += stackLength;
        }
        log_text(DR_LOG_ERROR, text, n);
        free(text);
    }
    if (message) JS_FreeCString(ctx, message);
    if (stack) JS_FreeCString(ctx, stack);
    JS_FreeValue(ctx, stackValue);
    JS_FreeValue(ctx, exception);
}

static int interrupt_handler(JSRuntime* runtime, void* opaque) {
    (void)runtime;
    (void)opaque;
    return dr_interrupted() != 0;
}

/* Promise reactions and other jobs queued while the guest ran, run to completion. */
static void run_pending_jobs(void) {
    JSContext* jobContext;
    for (;;) {
        int state = JS_ExecutePendingJob(rt, &jobContext);
        if (state <= 0) {
            if (state < 0) {
                report_exception("a job");
                continue;
            }
            break;
        }
    }
}

static void on_promise_rejection(JSContext* c, JSValueConst promise, JSValueConst reason, bool isHandled, void* opaque) {
    (void)c;
    (void)promise;
    (void)opaque;
    if (isHandled) {
        return;
    }
    JSValue copy = JS_DupValue(ctx, reason);
    JS_Throw(ctx, copy);
    report_exception("an unhandled promise rejection");
}

/* --- JavaScript -> CBOR ---------------------------------------------------------------------------------------- */

static bool encode_value(cbor_writer* w, JSValueConst value, int depth);

static int32_t handle_of(JSValueConst value) {
    void* opaque = JS_GetOpaque(value, hostObjectClassId);
    return (int32_t)(intptr_t)opaque;
}

static bool encode_callback(cbor_writer* w, JSValueConst function) {
    JSValue result = JS_Call(ctx, hookRegisterCallback, JS_UNDEFINED, 1, &function);
    if (JS_IsException(result)) {
        return false;
    }
    int32_t id = 0;
    JS_ToInt32(ctx, &id, result);
    JS_FreeValue(ctx, result);
    cw_callback(w, id);
    return true;
}

static bool encode_array(cbor_writer* w, JSValueConst array, int depth) {
    int64_t length = 0;
    if (JS_GetLength(ctx, array, &length) < 0) {
        return false;
    }
    cw_array(w, (size_t)length);
    for (int64_t i = 0; i < length; ++i) {
        JSValue element = JS_GetPropertyInt64(ctx, array, i);
        if (JS_IsException(element)) {
            return false;
        }
        bool ok = encode_value(w, element, depth + 1);
        JS_FreeValue(ctx, element);
        if (!ok) {
            return false;
        }
    }
    return true;
}

static bool encode_object(cbor_writer* w, JSValueConst object, int depth) {
    JSPropertyEnum* names = NULL;
    uint32_t count = 0;
    if (JS_GetOwnPropertyNames(ctx, &names, &count, object, JS_GPN_STRING_MASK | JS_GPN_ENUM_ONLY) < 0) {
        return false;
    }
    /* undefined members are left out, as JSON.stringify leaves them out */
    JSValue* values = count ? (JSValue*)malloc(sizeof(JSValue) * count) : NULL;
    size_t kept = 0;
    bool ok = true;
    for (uint32_t i = 0; i < count && ok; ++i) {
        JSValue v = JS_GetProperty(ctx, object, names[i].atom);
        if (JS_IsException(v)) {
            ok = false;
            values[i] = JS_UNDEFINED;
            break;
        }
        values[i] = v;
        if (!JS_IsUndefined(v)) {
            ++kept;
        }
    }
    if (ok) {
        cw_map(w, kept);
        for (uint32_t i = 0; i < count && ok; ++i) {
            if (JS_IsUndefined(values[i])) {
                continue;
            }
            size_t keyLength = 0;
            const char* key = JS_AtomToCStringLen(ctx, &keyLength, names[i].atom);
            if (!key) {
                ok = false;
                break;
            }
            cw_text_n(w, key, keyLength);
            JS_FreeCString(ctx, key);
            ok = encode_value(w, values[i], depth + 1);
        }
    }
    for (uint32_t i = 0; i < count; ++i) {
        if (!JS_IsUninitialized(values[i])) {
            JS_FreeValue(ctx, values[i]);
        }
    }
    free(values);
    JS_FreePropertyEnum(ctx, names, count);
    return ok;
}

static bool encode_bytes_view(cbor_writer* w, JSValueConst view) {
    size_t offset = 0;
    size_t length = 0;
    size_t perElement = 0;
    JSValue buffer = JS_GetTypedArrayBuffer(ctx, view, &offset, &length, &perElement);
    if (JS_IsException(buffer)) {
        return false;
    }
    size_t size = 0;
    uint8_t* data = JS_GetArrayBuffer(ctx, &size, buffer);
    bool ok = data != NULL && offset + length <= size;
    if (ok) {
        cw_bytes(w, data + offset, length);
    }
    JS_FreeValue(ctx, buffer);
    return ok;
}

static bool encode_date(cbor_writer* w, JSValueConst date) {
    JSValue method = JS_GetPropertyStr(ctx, date, "toISOString");
    JSValue text = JS_Call(ctx, method, date, 0, NULL);
    JS_FreeValue(ctx, method);
    if (JS_IsException(text)) {
        return false;
    }
    size_t length = 0;
    const char* s = JS_ToCStringLen(ctx, &length, text);
    bool ok = s != NULL;
    if (ok) {
        cw_text_n(w, s, length);
        JS_FreeCString(ctx, s);
    }
    JS_FreeValue(ctx, text);
    return ok;
}

static bool encode_value(cbor_writer* w, JSValueConst value, int depth) {
    if (depth > MAX_ENCODE_DEPTH) {
        JS_ThrowRangeError(ctx, "a value nested deeper than %d levels (a cycle?) cannot be passed to the host", MAX_ENCODE_DEPTH);
        return false;
    }
    int tag = JS_VALUE_GET_NORM_TAG(value);
    switch (tag) {
        case JS_TAG_UNDEFINED:
        case JS_TAG_UNINITIALIZED:
            cw_byte(w, 0xf7);  /* CBOR undefined */
            return true;
        case JS_TAG_NULL:
            cw_null(w);
            return true;
        case JS_TAG_BOOL:
            cw_bool(w, JS_VALUE_GET_BOOL(value));
            return true;
        case JS_TAG_INT:
            cw_int(w, JS_VALUE_GET_INT(value));
            return true;
        case JS_TAG_FLOAT64: {
            double d = JS_VALUE_GET_FLOAT64(value);
            cw_double(w, d);
            return true;
        }
        case JS_TAG_BIG_INT: {
            int64_t i = 0;
            if (JS_ToBigInt64(ctx, &i, value) < 0) {
                return false;
            }
            cw_int(w, i);
            return true;
        }
        case JS_TAG_STRING:
        case JS_TAG_STRING_ROPE: {
            size_t length = 0;
            const char* s = JS_ToCStringLen(ctx, &length, value);
            if (!s) {
                return false;
            }
            cw_text_n(w, s, length);
            JS_FreeCString(ctx, s);
            return true;
        }
        case JS_TAG_SYMBOL:
            JS_ThrowTypeError(ctx, "a symbol cannot be passed to the host");
            return false;
        case JS_TAG_OBJECT: {
            int32_t handle = handle_of(value);
            if (handle) {
                cw_object(w, handle);
                return true;
            }
            if (JS_IsFunction(ctx, value)) {
                return encode_callback(w, value);
            }
            if (JS_IsArray(value)) {
                return encode_array(w, value, depth);
            }
            if (JS_IsArrayBuffer(value)) {
                size_t size = 0;
                uint8_t* data = JS_GetArrayBuffer(ctx, &size, value);
                if (!data && size) {
                    return false;
                }
                cw_bytes(w, data, size);
                return true;
            }
            if (JS_GetTypedArrayType(value) >= 0 || JS_IsDataView(value)) {
                return encode_bytes_view(w, value);
            }
            if (JS_IsDate(value)) {
                return encode_date(w, value);
            }
            return encode_object(w, value, depth);
        }
        default:
            JS_ThrowTypeError(ctx, "a value of this kind cannot be passed to the host");
            return false;
    }
}

/* --- CBOR -> JavaScript ---------------------------------------------------------------------------------------- */

static JSValue decode_item(cbor_reader* r, cbor_item* head);

static JSValue decode_next(cbor_reader* r) {
    cbor_item item;
    if (!cr_next(r, &item)) {
        return JS_ThrowInternalError(ctx, "malformed CBOR from the host");
    }
    return decode_item(r, &item);
}

static JSValue decode_array(cbor_reader* r, size_t count) {
    JSValue array = JS_NewArray(ctx);
    for (size_t i = 0; i < count; ++i) {
        JSValue element = decode_next(r);
        if (JS_IsException(element)) {
            JS_FreeValue(ctx, array);
            return element;
        }
        if (JS_SetPropertyInt64(ctx, array, (int64_t)i, element) < 0) {
            JS_FreeValue(ctx, array);
            return JS_EXCEPTION;
        }
    }
    return array;
}

static JSValue decode_map(cbor_reader* r, size_t count) {
    JSValue object = JS_NewObject(ctx);
    int32_t objectHandle = 0;
    JSValue className = JS_UNDEFINED;
    for (size_t i = 0; i < count; ++i) {
        cbor_item key;
        if (!cr_next(r, &key)) {
            JS_FreeValue(ctx, object);
            JS_FreeValue(ctx, className);
            return JS_ThrowInternalError(ctx, "malformed CBOR map from the host");
        }
        if (key.type == CBOR_TEXT && key.n == 7 && memcmp(key.s, "@object", 7) == 0) {
            cbor_item handle;
            if (!cr_next(r, &handle)) {
                JS_FreeValue(ctx, object);
                JS_FreeValue(ctx, className);
                return JS_ThrowInternalError(ctx, "malformed CBOR object record from the host");
            }
            objectHandle = (int32_t)cr_number(&handle);
            continue;
        }
        JSValue value = decode_next(r);
        if (JS_IsException(value)) {
            JS_FreeValue(ctx, object);
            JS_FreeValue(ctx, className);
            return value;
        }
        if (key.type == CBOR_TEXT && key.n == 6 && memcmp(key.s, "@class", 6) == 0) {
            JS_FreeValue(ctx, className);
            className = value;
            continue;
        }
        JSValue keyValue;
        if (key.type == CBOR_TEXT) {
            keyValue = JS_NewStringLen(ctx, (const char*)key.s, key.n);
        } else if (key.type == CBOR_UINT || key.type == CBOR_NINT || key.type == CBOR_FLOAT) {
            keyValue = JS_NewFloat64(ctx, cr_number(&key));
        } else {
            JS_FreeValue(ctx, value);
            continue;  /* a key of a kind JavaScript has no property for */
        }
        JSAtom atom = JS_ValueToAtom(ctx, keyValue);
        JS_FreeValue(ctx, keyValue);
        int defined = JS_DefinePropertyValue(ctx, object, atom, value, JS_PROP_C_W_E);
        JS_FreeAtom(ctx, atom);
        if (defined < 0) {
            JS_FreeValue(ctx, object);
            JS_FreeValue(ctx, className);
            return JS_EXCEPTION;
        }
    }
    if (objectHandle) {
        /* a host object: the shim's wrapper for the handle, one per handle */
        JS_FreeValue(ctx, object);
        JSValue args[2] = { JS_NewInt32(ctx, objectHandle), className };
        JSValue wrapped = JS_Call(ctx, hookWrapObject, JS_UNDEFINED, 2, args);
        JS_FreeValue(ctx, className);
        return wrapped;
    }
    JS_FreeValue(ctx, className);
    return object;
}

static JSValue decode_item(cbor_reader* r, cbor_item* item) {
    switch (item->type) {
        case CBOR_UINT:
        case CBOR_NINT:
            if (item->integer >= INT32_MIN && item->integer <= INT32_MAX) {
                return JS_NewInt32(ctx, (int32_t)item->integer);
            }
            if (item->type == CBOR_UINT && (uint64_t)item->integer > (uint64_t)INT64_MAX) {
                return JS_NewFloat64(ctx, item->number);
            }
            return JS_NewInt64(ctx, item->integer);
        case CBOR_FLOAT:
            return JS_NewFloat64(ctx, item->number);
        case CBOR_TEXT:
            return JS_NewStringLen(ctx, (const char*)item->s, item->n);
        case CBOR_BYTES:
            return JS_NewArrayBufferCopy(ctx, item->s, item->n);
        case CBOR_ARRAY:
            return decode_array(r, item->n);
        case CBOR_MAP:
            return decode_map(r, item->n);
        case CBOR_TAG:
            return decode_next(r);
        case CBOR_TRUE:
            return JS_TRUE;
        case CBOR_FALSE:
            return JS_FALSE;
        case CBOR_NULL:
            return JS_NULL;
        case CBOR_UNDEFINED:
            return JS_UNDEFINED;
        default:
            return JS_ThrowInternalError(ctx, "malformed CBOR item from the host");
    }
}

/* An error of the record's type: a real TypeError, SyntaxError and so on for JavaScript's own types (instanceof
   works, as it did for QtScript's errors), otherwise an Error whose name is the type. */
static JSValue make_error_of_type(JSValueConst type, JSValueConst message) {
    static const char* const STANDARD[] = { "Error", "TypeError", "SyntaxError", "RangeError", "ReferenceError", "EvalError", "URIError", NULL };
    JSValue text = JS_IsUndefined(message) ? JS_NewString(ctx, "") : JS_DupValue(ctx, message);
    JSValue error = JS_UNDEFINED;
    if (JS_IsString(type)) {
        const char* name = JS_ToCString(ctx, type);
        int standard = 0;
        for (int i = 0; name && STANDARD[i]; i++) {
            if (strcmp(name, STANDARD[i]) == 0) {
                standard = 1;
                break;
            }
        }
        if (standard) {
            JSValue global = JS_GetGlobalObject(ctx);
            JSValue constructor = JS_GetPropertyStr(ctx, global, name);
            JS_FreeValue(ctx, global);
            if (JS_IsConstructor(ctx, constructor)) {
                error = JS_CallConstructor(ctx, constructor, 1, &text);
                if (JS_IsException(error)) {
                    JS_FreeValue(ctx, JS_GetException(ctx));
                    error = JS_UNDEFINED;
                }
            }
            JS_FreeValue(ctx, constructor);
        }
        if (name) JS_FreeCString(ctx, name);
    }
    if (JS_IsUndefined(error)) {
        error = JS_NewError(ctx);
        JS_DefinePropertyValueStr(ctx, error, "message", JS_DupValue(ctx, text), JS_PROP_WRITABLE | JS_PROP_CONFIGURABLE);
        if (JS_IsString(type)) {
            JS_DefinePropertyValueStr(ctx, error, "name", JS_DupValue(ctx, type), JS_PROP_WRITABLE | JS_PROP_CONFIGURABLE);
        }
    }
    JS_FreeValue(ctx, text);
    return error;
}

/* The bytes a host function returned: decoded and freed. A top-level error record becomes a thrown error of the
   record's type. */
static JSValue take_result(int64_t packed) {
    dr_bytes bytes = dr_unpack(packed);
    if (!bytes.data) {
        return JS_UNDEFINED;
    }
    cbor_reader r = cr_from(bytes);
    JSValue value = decode_next(&r);
    dr_bytes_free(bytes);
    if (JS_IsException(value) || !JS_IsObject(value)) {
        return value;
    }
    JSValue record = JS_GetPropertyStr(ctx, value, "@error");
    if (JS_IsObject(record)) {
        JSValue type = JS_GetPropertyStr(ctx, record, "type");
        JSValue message = JS_GetPropertyStr(ctx, record, "message");
        JSValue error = make_error_of_type(type, message);
        JS_FreeValue(ctx, type);
        JS_FreeValue(ctx, message);
        JS_FreeValue(ctx, record);
        JS_FreeValue(ctx, value);
        return JS_Throw(ctx, error);
    }
    JS_FreeValue(ctx, record);
    return value;
}

/* --- the native functions the shim receives -------------------------------------------------------------------- */

/* The handle of a host object argument, or an integer handle given directly. */
static int32_t argument_handle(JSValueConst value) {
    int32_t handle = handle_of(value);
    if (!handle && JS_IsNumber(value)) {
        JS_ToInt32(ctx, &handle, value);
    }
    return handle;
}

static JSValue js_version(JSContext* c, JSValueConst thisValue, int argc, JSValueConst* argv) {
    (void)c; (void)thisValue; (void)argc; (void)argv;
    return JS_NewInt32(ctx, dr_version());
}

static JSValue js_globals(JSContext* c, JSValueConst thisValue, int argc, JSValueConst* argv) {
    (void)c; (void)thisValue; (void)argc; (void)argv;
    return take_result(dr_globals());
}

static JSValue js_describe(JSContext* c, JSValueConst thisValue, int argc, JSValueConst* argv) {
    (void)c; (void)thisValue;
    cbor_writer w;
    cw_init(&w);
    if (argc < 1 || !encode_value(&w, argv[0], 0)) {
        cw_free(&w);
        return JS_IsException(JS_UNDEFINED) ? JS_EXCEPTION : JS_ThrowTypeError(ctx, "describe takes a global's name or a host object");
    }
    int64_t packed = dr_describe(w.data, (int32_t)w.length);
    cw_free(&w);
    return take_result(packed);
}

static JSValue js_call(JSContext* c, JSValueConst thisValue, int argc, JSValueConst* argv) {
    (void)c; (void)thisValue;
    if (argc < 2) {
        return JS_ThrowTypeError(ctx, "call(object, method, arguments)");
    }
    int32_t handle = argument_handle(argv[0]);
    size_t nameLength = 0;
    const char* name = JS_ToCStringLen(ctx, &nameLength, argv[1]);
    if (!name) {
        return JS_EXCEPTION;
    }
    cbor_writer w;
    cw_init(&w);
    bool ok;
    if (argc >= 3 && JS_IsArray(argv[2])) {
        ok = encode_array(&w, argv[2], 0);
    } else {
        cw_array(&w, 0);
        ok = true;
    }
    if (!ok) {
        cw_free(&w);
        JS_FreeCString(ctx, name);
        return JS_EXCEPTION;
    }
    int64_t packed = dr_call(handle, name, (int32_t)nameLength, w.data, (int32_t)w.length);
    cw_free(&w);
    JS_FreeCString(ctx, name);
    return take_result(packed);
}

static JSValue js_get(JSContext* c, JSValueConst thisValue, int argc, JSValueConst* argv) {
    (void)c; (void)thisValue;
    if (argc < 2) {
        return JS_ThrowTypeError(ctx, "get(object, property)");
    }
    int32_t handle = argument_handle(argv[0]);
    size_t nameLength = 0;
    const char* name = JS_ToCStringLen(ctx, &nameLength, argv[1]);
    if (!name) {
        return JS_EXCEPTION;
    }
    int64_t packed = dr_get(handle, name, (int32_t)nameLength);
    JS_FreeCString(ctx, name);
    return take_result(packed);
}

static JSValue js_set(JSContext* c, JSValueConst thisValue, int argc, JSValueConst* argv) {
    (void)c; (void)thisValue;
    if (argc < 3) {
        return JS_ThrowTypeError(ctx, "set(object, property, value)");
    }
    int32_t handle = argument_handle(argv[0]);
    size_t nameLength = 0;
    const char* name = JS_ToCStringLen(ctx, &nameLength, argv[1]);
    if (!name) {
        return JS_EXCEPTION;
    }
    cbor_writer w;
    cw_init(&w);
    if (!encode_value(&w, argv[2], 0)) {
        cw_free(&w);
        JS_FreeCString(ctx, name);
        return JS_EXCEPTION;
    }
    int64_t packed = dr_set(handle, name, (int32_t)nameLength, w.data, (int32_t)w.length);
    cw_free(&w);
    JS_FreeCString(ctx, name);
    JSValue result = take_result(packed);
    if (JS_IsException(result)) {
        return result;
    }
    JS_FreeValue(ctx, result);
    return JS_UNDEFINED;
}

/* host.method(name), host.getter(name) and host.setter(name): a native function bound to a member's name and called
   with the host object as `this`. A script's call reaches the host with no JavaScript function in between and with
   its arguments encoded where they are, not copied into an array first: the shim builds every host object's
   methods and accessors from these. */
static JSValue js_method_call(JSContext* c, JSValueConst thisValue, int argc, JSValueConst* argv, int magic, JSValueConst* data) {
    (void)c; (void)magic;
    int32_t handle = argument_handle(thisValue);
    size_t nameLength = 0;
    const char* name = JS_ToCStringLen(ctx, &nameLength, data[0]);
    if (!name) {
        return JS_EXCEPTION;
    }
    cbor_writer w;
    cw_init(&w);
    cw_array(&w, (size_t)argc);
    for (int i = 0; i < argc; ++i) {
        if (!encode_value(&w, argv[i], 1)) {
            cw_free(&w);
            JS_FreeCString(ctx, name);
            return JS_EXCEPTION;
        }
    }
    int64_t packed = dr_call(handle, name, (int32_t)nameLength, w.data, (int32_t)w.length);
    cw_free(&w);
    JS_FreeCString(ctx, name);
    return take_result(packed);
}

static JSValue js_getter_call(JSContext* c, JSValueConst thisValue, int argc, JSValueConst* argv, int magic, JSValueConst* data) {
    (void)c; (void)argc; (void)argv; (void)magic;
    int32_t handle = argument_handle(thisValue);
    size_t nameLength = 0;
    const char* name = JS_ToCStringLen(ctx, &nameLength, data[0]);
    if (!name) {
        return JS_EXCEPTION;
    }
    int64_t packed = dr_get(handle, name, (int32_t)nameLength);
    JS_FreeCString(ctx, name);
    return take_result(packed);
}

static JSValue js_setter_call(JSContext* c, JSValueConst thisValue, int argc, JSValueConst* argv, int magic, JSValueConst* data) {
    (void)c; (void)magic;
    int32_t handle = argument_handle(thisValue);
    size_t nameLength = 0;
    const char* name = JS_ToCStringLen(ctx, &nameLength, data[0]);
    if (!name) {
        return JS_EXCEPTION;
    }
    cbor_writer w;
    cw_init(&w);
    if (!encode_value(&w, argc > 0 ? argv[0] : JS_UNDEFINED, 0)) {
        cw_free(&w);
        JS_FreeCString(ctx, name);
        return JS_EXCEPTION;
    }
    int64_t packed = dr_set(handle, name, (int32_t)nameLength, w.data, (int32_t)w.length);
    cw_free(&w);
    JS_FreeCString(ctx, name);
    JSValue result = take_result(packed);
    if (JS_IsException(result)) {
        return result;
    }
    JS_FreeValue(ctx, result);
    return JS_UNDEFINED;
}

