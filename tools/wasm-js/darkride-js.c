/* evaluate(source, fileName): global code under the file's name, so stack traces read right. */
static JSValue js_evaluate(JSContext* c, JSValueConst thisValue, int argc, JSValueConst* argv) {
    (void)c; (void)thisValue;
    if (argc < 1) {
        return JS_ThrowTypeError(ctx, "evaluate(source, fileName)");
    }
    size_t sourceLength = 0;
    const char* source = JS_ToCStringLen(ctx, &sourceLength, argv[0]);
    if (!source) {
        return JS_EXCEPTION;
    }
    const char* fileName = argc >= 2 && JS_IsString(argv[1]) ? JS_ToCString(ctx, argv[1]) : NULL;
    JSValue result = JS_Eval(ctx, source, sourceLength, fileName ? fileName : "(script)", JS_EVAL_TYPE_GLOBAL);
    if (fileName) {
        JS_FreeCString(ctx, fileName);
    }
    JS_FreeCString(ctx, source);
    return result;
}

